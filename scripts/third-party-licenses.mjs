// Rigenera THIRD_PARTY_LICENSES.md dalle dipendenze installate (npm run licenses).
// Elenca le dipendenze di runtime (dirette e indirette, quelle che finiscono nella build o la
// producono) e gli strumenti di sviluppo diretti.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url).pathname;
const pkg = JSON.parse(readFileSync(`${root}package.json`, 'utf8'));

function info(dir) {
  const j = JSON.parse(readFileSync(`${dir}/package.json`, 'utf8'));
  let repo = j.repository?.url ?? j.repository ?? j.homepage ?? '';
  repo = String(repo).replace(/^git\+/, '').replace(/^git@github\.com:/, 'https://github.com/').replace(/\.git$/, '');
  const license = j.license ?? (j.licenses ?? []).map((l) => l.type).join(' OR ') ?? 'UNKNOWN';
  return { name: j.name, version: j.version, license, repo };
}

// tutte le dipendenze di produzione risolte da npm
const paths = execFileSync('npm', ['ls', '--omit=dev', '--all', '--parseable'], { cwd: root, encoding: 'utf8' })
  .trim()
  .split('\n')
  .filter((p) => p.includes('node_modules'));
const runtime = new Map();
for (const p of paths) {
  const i = info(p);
  runtime.set(`${i.name}@${i.version}`, { ...i, direct: i.name in pkg.dependencies });
}
const dev = Object.keys(pkg.devDependencies).map((n) => info(`${root}node_modules/${n}`));

const row = (d) => `| ${d.direct ? `**${d.name}**` : d.name} | ${d.version} | ${d.license} | ${d.repo} |`;
const sorted = [...runtime.values()].sort((a, b) => Number(b.direct) - Number(a.direct) || a.name.localeCompare(b.name));

const md = `# Third-party licenses / Licenze di terze parti

rrstudio Tools (AGPL-3.0-or-later) uses the following free and open source components. Each one is
distributed under its own license; the full texts are in each package (\`node_modules/<name>/LICENSE\`)
and in the linked repositories. All of them are compatible with the AGPL-3.0.

rrstudio Tools usa i componenti open source elencati qui sotto, ognuno con la sua licenza.

> Generated by \`npm run licenses\` / Generato con \`npm run licenses\`. Direct dependencies in **bold**.

## Runtime (included in the build / inclusi nella build)

| Package | Version | License | Source |
|---|---|---|---|
${sorted.map(row).join('\n')}

### Notes / Note
- **SheetJS Community Edition** (\`xlsx\`) is installed from the official SheetJS CDN tarball
  (\`https://cdn.sheetjs.com/\`), Apache-2.0. Only the build process downloads it: the website never
  contacts external servers.
- **Inter Tight** and **JetBrains Mono** fonts (via Fontsource) are licensed under the SIL Open Font
  License 1.1 and are served from the same origin as the site.
- **Apache ECharts** is a project of the Apache Software Foundation (Apache-2.0); see its NOTICE file.

## Development tools (not shipped / non distribuiti)

| Package | Version | License | Source |
|---|---|---|---|
${dev.map(row).join('\n')}
`;
writeFileSync(`${root}THIRD_PARTY_LICENSES.md`, md);
console.log(`THIRD_PARTY_LICENSES.md: ${runtime.size} runtime, ${dev.length} dev`);
